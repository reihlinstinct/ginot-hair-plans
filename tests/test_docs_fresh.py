"""Regression tests for #539: CI must catch a src/ginot change whose
committed docs/ was not regenerated (#531 shipped a page.py change without
docs/, so the merge deployed nothing; #538 regenerated it by hand).

The tests render from the repo's committed inputs into a temp docs/ tree with
a pinned synthetic date, so they do not depend on the state of the real docs/.
"""
import shutil
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).parent.parent
sys.path.insert(0, str(ROOT / "scripts" / "ci"))

import check_docs_fresh as fresh

DATE = "2026-01-15"


@pytest.fixture(scope="module")
def clean_tree(tmp_path_factory):
    """A docs/ tree regenerated by the check's own --write path."""
    docs = tmp_path_factory.mktemp("clean") / "docs"
    docs.mkdir()
    (docs / "index.html").write_text(f"<p>עודכן: {DATE}.</p>", encoding="utf-8")
    assert fresh.check(docs, write=True) == []
    return docs


@pytest.fixture
def docs(clean_tree, tmp_path):
    out = tmp_path / "docs"
    shutil.copytree(clean_tree, out)
    return out


def test_clean_generated_tree_passes(docs):
    assert fresh.check(docs) == []
    assert fresh.main(["--docs", str(docs)]) == 0


def test_stale_index_html_fails(docs):
    """The #531 shape: the template changed, the committed page did not."""
    index = docs / "index.html"
    index.write_text(
        index.read_text(encoding="utf-8").replace("</body>", "<p>old</p></body>", 1),
        encoding="utf-8",
    )
    problems = fresh.check(docs)
    assert [p.split(":")[0] for p in problems] == ["index.html"]
    assert fresh.main(["--docs", str(docs)]) == 1


@pytest.mark.parametrize("name", ["plan-map.js", "style.css", "permits.html"])
def test_stale_static_or_fragment_fails(docs, name):
    target = docs / name
    target.write_bytes(target.read_bytes() + b"\n/* stale */\n")
    assert [p.split(":")[0] for p in fresh.check(docs)] == [name]


def test_rendered_file_missing_from_docs_fails(docs):
    (docs / "rows.html").unlink()
    assert any(p.startswith("rows.html: rendered but missing") for p in fresh.check(docs))


def test_crlf_only_difference_is_not_stale(docs):
    """Permit descriptions carry CR LF that committed copies do not keep."""
    about = docs / "about.html"
    about.write_bytes(about.read_bytes().replace(b"\n", b"\r\n"))
    assert fresh.check(docs) == []


def test_each_file_is_compared_at_its_own_stamp_date(docs):
    """A permit-feed batch or a hand regeneration can leave about.html or a
    review page on an older generated date than index.html; that is not
    drift, but content changes at that date still are."""
    about = docs / "about.html"
    about.write_text(
        about.read_text(encoding="utf-8").replace(DATE, "2026-01-10"), encoding="utf-8"
    )
    assert fresh.check(docs) == []
    about.write_text(
        about.read_text(encoding="utf-8").replace("</body>", "<p>x</p></body>", 1),
        encoding="utf-8",
    )
    problems = fresh.check(docs)
    assert len(problems) == 1 and problems[0].startswith("about.html: stale")
    assert "generated=2026-01-10" in problems[0]


def test_png_and_excluded_outputs_are_not_compared(docs):
    (docs / "og.png").write_bytes(b"not a png")
    (docs / "data.json").write_text("{}", encoding="utf-8")
    assert fresh.check(docs) == []
    listed = fresh.uncovered(docs)
    assert "og.png" in listed
    assert any(n.startswith("data.json (") for n in listed)


def test_missing_date_stamp_is_a_check_error_not_a_pass(tmp_path):
    docs = tmp_path / "docs"
    docs.mkdir()
    (docs / "index.html").write_text("<p>no stamp</p>", encoding="utf-8")
    with pytest.raises(fresh.CheckError):
        fresh.check(docs)
    assert fresh.main(["--docs", str(docs)]) == 2

